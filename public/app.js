function renderCarrossel() {
  const carrosselInner = document.getElementById('carrossel-inner');
  const indicadores = document.getElementById('carrossel-indicadores');
  if (!carrosselInner) return;

 const selecoes = JSON.parse(localStorage.getItem('selecoes')) || [];
 const destaques = selecoes.filter(s => s.destaque);
 
  destaques.forEach((selecao, index) => {
   
    const slide = document.createElement('div');
    slide.className = `carousel-item${index === 0 ? ' active' : ''}`;
    slide.innerHTML = `
      <div class="row align-items-center g-0 px-3 px-md-5">
        <div class="col-md-6 text-center py-4">
          <img src="${selecao.imagem_principal}" class="img-fluid rounded shadow" alt="Camisa ${selecao.nome}" style="max-height:420px; object-fit:cover;">
        </div>
        <div class="col-md-6 text-white py-4 px-4">
          <span class="badge bg-warning text-dark mb-2">${selecao.copa}</span>
          <h2 class="fw-bold display-6">${selecao.nome}</h2>
          <p class="lead">${selecao.descricao}</p>
          <p class="text-white-50 small mb-3"><strong>Fabricante:</strong> ${selecao.fabricante} &nbsp;|&nbsp; <strong>Tipo:</strong> ${selecao.tipo}</p>
          <a href="detalhe.html?tipo=selecao&id=${selecao.id}" class="btn btn-warning fw-bold">Ver Detalhes</a>
        </div>
      </div>
    `;
    carrosselInner.appendChild(slide);


    const btn = document.createElement('button');
    btn.type = 'button';
    btn.setAttribute('data-bs-target', '#carrosselCamisas');
    btn.setAttribute('data-bs-slide-to', index);
    if (index === 0) { btn.className = 'active'; btn.setAttribute('aria-current', 'true'); }
    btn.setAttribute('aria-label', `Slide ${index + 1}`);
    indicadores.appendChild(btn);
  });
}


